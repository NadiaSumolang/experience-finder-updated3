-- Skema Experience Finder. Jalankan seluruh SQL ini di Supabase > SQL Editor.
-- Cerita lengkap dan komentar hanya dapat dibaca oleh pengguna yang sudah login.
-- Jangan menaruh service_role key di frontend.

create table if not exists public.stories (
  id bigint generated by default as identity primary key,
  story_key text not null unique,
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'Pengguna',
  category text not null,
  situation text not null,
  title text not null,
  happened text not null,
  did text not null,
  unexpected text not null default '',
  lesson text not null,
  repeat text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists stories_created_at_idx on public.stories (created_at desc);
create index if not exists stories_story_key_idx on public.stories (story_key);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  story_key text not null,
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'Pengguna',
  body text not null check (char_length(body) between 1 and 1200),
  created_at timestamptz not null default now()
);

create index if not exists comments_story_created_idx on public.comments (story_key, created_at asc);

alter table public.stories enable row level security;
alter table public.comments enable row level security;

drop policy if exists "Stories are readable by everyone" on public.stories;
drop policy if exists "Signed-in users can read stories" on public.stories;
create policy "Signed-in users can read stories"
  on public.stories for select to authenticated
  using (auth.uid() is not null);

drop policy if exists "Signed-in users can publish their own stories" on public.stories;
create policy "Signed-in users can publish their own stories"
  on public.stories for insert to authenticated
  with check (auth.uid() = author_id);

drop policy if exists "Authors can delete their own stories" on public.stories;
create policy "Authors can delete their own stories"
  on public.stories for delete to authenticated
  using (auth.uid() = author_id);

drop policy if exists "Comments are readable by everyone" on public.comments;
drop policy if exists "Signed-in users can read comments" on public.comments;
create policy "Signed-in users can read comments"
  on public.comments for select to authenticated
  using (auth.uid() is not null);

drop policy if exists "Signed-in users can post comments as themselves" on public.comments;
create policy "Signed-in users can post comments as themselves"
  on public.comments for insert to authenticated
  with check (auth.uid() = author_id);

drop policy if exists "Authors can delete their own comments" on public.comments;
create policy "Authors can delete their own comments"
  on public.comments for delete to authenticated
  using (auth.uid() = author_id);

